/*
 * band_art.h -- the main menu's safety band, 320x40, one bit per pixel.
 *
 * The band is a picture, not composed text: the game's font sheet is ASCII
 * only, so the Japanese sentence cannot be glyphs. It lives at VRAM (320,256),
 * 320 texels wide and 40 tall, 4bpp, palette at (512,244) -- a dark green
 * ground with white anti-aliased text, fifteen colours in all.
 *
 * Being 320 wide, it straddles the 256-texel boundary between two texture
 * pages, which is why the game draws it as two rectangles. That is a drawing
 * detail, not a storage one: in VRAM the pixels are contiguous, so the
 * replacement is a single transfer.
 *
 * One bit per pixel throws the anti-aliasing away -- the replacement is flat
 * ink on flat ground. The palette indices are not baked in: the background
 * index is read from the region's own top-left texel (a corner is background
 * by construction) and the ink index is the brightest entry of the palette.
 *
 * Row-major, 40 bytes per row, bit 7 leftmost. Generated -- do not hand-edit.
 */
