#define HINTBAR_INK 15   /* white in both halves' palettes */
#define HINTBAR_BG   0   /* transparent ground, as in the original */

/* FNV-1a over the raw 4bpp indices of the two windows, top row first. The
 * replacement fires only on this exact picture: the page is reused between
 * screens, and once our own English is in place the hash no longer matches,
 * which is what stops it from being repainted every frame.
 *
 * Bit 15 of each halfword is masked off before the indices are read. It is
 * ordinary texel data in a texture, but a VRAM snapshot written as RGB
 * cannot carry it, and this number was measured from such a snapshot -- so
 * the runtime has to drop it too or the two never agree. */
#define HINTBAR_JP_HASH 0xFFBCFAE4u

