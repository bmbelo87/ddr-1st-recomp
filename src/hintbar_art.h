/*
 * hintbar_art.h -- the "how to use the pad" bar at the foot of PLAY MODE
 * SELECT and MUSIC SELECT, 224x16, one bit per pixel.
 *
 * The Japanese reads "botan de sentaku / botan de kettei" -- pick with the
 * left/right buttons, confirm with the circle button. It is a picture, not
 * composed text, so it has to be repainted rather than retyped.
 *
 * The same 224x16 picture is stored twice, once per screen, at VRAM (320,208)
 * and (640,24); both are 4bpp and both decode through the same pair of
 * palettes, so one replacement serves both. The game draws each as two
 * quads that meet at texel 120, the left half through one palette and the
 * right half through another -- index 15 is white in both, which is why the
 * replacement can use a single ink index across the whole strip.
 *
 * Only the two text windows are repainted. The left/right arrows (texels
 * 0..31) and the circle (texels 120..135) are not Japanese and are drawn in
 * several colours, so they are copied through from VRAM untouched.
 *
 * Row-major over the full 224, 28 bytes per row, bit 7 leftmost; the bits
 * outside the two windows are zero and are never used. Generated -- do not
 * hand-edit.
 */
